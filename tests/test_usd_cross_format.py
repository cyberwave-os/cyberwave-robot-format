# The USD layer comment carries the package version, so a golden .usda would go stale
# on every release. Blank it on both sides and assert the live version separately.
_GENERATED_BY = re.compile(r"(Generated by cyberwave-robot-format )\S+")


def _version_agnostic(usda: str) -> str:
    return _GENERATED_BY.sub(r"\g<1>*", usda)


